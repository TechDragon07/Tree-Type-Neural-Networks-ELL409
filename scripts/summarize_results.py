"""Generate LaTeX macros and Markdown directly from committed run artifacts."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from tree_nn.analysis import repeated_seed_double_descent

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "outputs"
REPORT = ROOT / "report"
DOCS = ROOT / "docs"


def _read(path: Path) -> Any:
    return json.loads(path.read_text())


def _pct(value: float) -> str:
    return f"{100 * value:.2f}"


def _main_result(dataset: str) -> dict[str, str]:
    directory = OUTPUTS / dataset / "main"
    if not (directory / "metrics.json").exists():
        return {"available": "no"}
    config = _read(directory / "config.json")
    metrics = _read(directory / "metrics.json")
    summary = _read(directory / "summary.json")
    root = [row for row in metrics if row["stage"] == "root"][-1]
    final = metrics[-1]
    return {
        "available": "yes",
        "train_n": str(config["train_size"]),
        "test_n": str(config["test_size"]),
        "root_train": _pct(root["train_accuracy"]),
        "root_test": _pct(root["test_accuracy"]),
        "root_train_loss": f"{root['train_loss']:.3f}",
        "root_test_loss": f"{root['test_loss']:.3f}",
        "final_train": _pct(final["train_accuracy"]),
        "final_test": _pct(final["test_accuracy"]),
        "final_train_loss": f"{final['train_loss']:.3f}",
        "final_test_loss": f"{final['test_loss']:.3f}",
        "train_gain": f"{100 * (final['train_accuracy'] - root['train_accuracy']):.2f}",
        "test_gain": f"{100 * (final['test_accuracy'] - root['test_accuracy']):.2f}",
        "nodes": str(final["nodes"]),
        "parameters": f"{int(summary['unpruned_parameters']):,}",
        "parameter_growth": (
            f"{100 * (summary['unpruned_parameters'] / root['parameters'] - 1):.1f}"
        ),
        "retained_nodes": str(len(summary["active_children_after_pruning"])),
        "pruned_parameters": f"{int(summary['pruned_parameters']):,}",
        "pruning_reduction": (
            f"{100 * (1 - summary['pruned_parameters'] / summary['unpruned_parameters']):.1f}"
        ),
        "pruned_train": _pct(summary["pruned_train_accuracy"]),
        "pruned_test": _pct(summary["pruned_test_accuracy"]),
        "interpolates": ("yes" if final["train_accuracy"] >= config["target_accuracy"] else "no"),
        "root_epoch": str(root["epoch"]),
        "root_target": _pct(config["root_target_accuracy"]),
        "prune_accuracy": _pct(config["prune_accuracy"]),
    }


def _sweep_result(dataset: str) -> dict[str, str]:
    sweep_name = next(
        (
            name
            for name in ("full_sweep", "interpolation_sweep", "double_descent")
            if (OUTPUTS / dataset / name / "capacity_sweep.json").exists()
        ),
        None,
    )
    if sweep_name is None:
        return {"available": "no"}
    path = OUTPUTS / dataset / sweep_name / "capacity_sweep.json"
    rows = _read(path)
    widths = sorted({int(row["width"]) for row in rows})
    established, supports, seed_count = repeated_seed_double_descent(rows)
    return {
        "available": "yes",
        "directory": sweep_name,
        "models": str(len(rows)),
        "seeds": str(seed_count),
        "widths": ", ".join(str(width) for width in widths),
        "supporting_seeds": str(supports),
        "criterion": "met" if established else "not met",
        "min_train": _pct(min(row["train_accuracy"] for row in rows)),
        "max_train": _pct(max(row["train_accuracy"] for row in rows)),
        "min_test": _pct(min(row["test_accuracy"] for row in rows)),
        "max_test": _pct(max(row["test_accuracy"] for row in rows)),
    }


def _macro_name(prefix: str, key: str) -> str:
    parts = key.split("_")
    return prefix + "".join(part.capitalize() for part in parts)


def _write_macros(results: dict[str, dict[str, str]]) -> None:
    lines = ["% Generated by scripts/summarize_results.py; do not edit by hand."]
    for prefix, values in results.items():
        for key, value in values.items():
            safe = value.replace("%", r"\%").replace("_", r"\_")
            lines.append(rf"\newcommand{{\{_macro_name(prefix, key)}}}{{{safe}}}")
    (REPORT / "results_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _describe_main(label: str, values: dict[str, str]) -> list[str]:
    if values["available"] == "no":
        return [f"### {label}", "", "No completed main run is available.", ""]
    return [
        f"### {label}",
        "",
        f"- Controlled subset: {values['train_n']} train / {values['test_n']} test.",
        (
            f"- Root: {values['root_train']}% train, {values['root_test']}% test "
            f"at epoch {values['root_epoch']}."
        ),
        (
            f"- Final tree: {values['final_train']}% train, "
            f"{values['final_test']}% test, {values['nodes']} accepted children."
        ),
        (
            f"- Change from root: {values['train_gain']} training points and "
            f"{values['test_gain']} test points; test cross-entropy "
            f"{values['root_test_loss']} → {values['final_test_loss']}."
        ),
        (
            f"- Interpolation criterion reached: {values['interpolates']}; "
            f"parameters: {values['parameters']}."
        ),
        (
            f"- Greedy pruning retained {values['retained_nodes']} children and "
            f"{values['pruned_parameters']} parameters "
            f"({values['pruning_reduction']}% reduction), with "
            f"{values['pruned_train']}% train / {values['pruned_test']}% test."
        ),
        "",
    ]


def _describe_sweep(label: str, values: dict[str, str]) -> list[str]:
    if values["available"] == "no":
        return [f"### {label}", "", "No completed capacity sweep is available.", ""]
    return [
        f"### {label}",
        "",
        (
            f"- {values['models']} independent models, {values['seeds']} seeds, "
            f"widths {values['widths']}."
        ),
        (
            f"- Train-accuracy range: {values['min_train']}–{values['max_train']}%; "
            f"test-accuracy range: {values['min_test']}–{values['max_test']}%."
        ),
        (
            f"- Supporting seeds: {values['supporting_seeds']}; repeated-seed "
            f"double-descent criterion: {values['criterion']}."
        ),
        "",
    ]


def _write_markdown(results: dict[str, dict[str, str]]) -> None:
    lines = [
        "# Measured Results",
        "",
        "This file is generated from JSON artifacts. Controlled-subset measurements "
        "are not full-dataset benchmarks.",
        "",
        "## Main tree-growth runs",
        "",
    ]
    lines.extend(_describe_main("CIFAR-10", results["Cifar"]))
    lines.extend(_describe_main("Cats vs Dogs", results["Pets"]))
    lines.extend(["## Capacity diagnostics", ""])
    lines.extend(_describe_sweep("CIFAR-10", results["CifarSweep"]))
    lines.extend(_describe_sweep("Cats vs Dogs", results["PetsSweep"]))
    if results["Cifar"]["available"] == "yes":
        lines.extend(
            [
                "## Interpretive findings",
                "",
                "### Memorization versus generalization",
                "",
                (
                    f"The CIFAR-10 corrections added {results['Cifar']['train_gain']} "
                    "training-accuracy points but only "
                    f"{results['Cifar']['test_gain']} test points. Test "
                    f"cross-entropy worsened from {results['Cifar']['root_test_loss']} "
                    f"to {results['Cifar']['final_test_loss']}. The tree therefore "
                    "memorized residuals without a corresponding generalization gain."
                ),
                "",
            ]
        )
    if results["Pets"]["available"] == "yes":
        lines.extend(
            [
                (
                    f"Cats vs Dogs is stronger negative evidence: corrections added "
                    f"{results['Pets']['train_gain']} training points but changed test "
                    f"accuracy by {results['Pets']['test_gain']} points, while test "
                    f"cross-entropy moved from {results['Pets']['root_test_loss']} to "
                    f"{results['Pets']['final_test_loss']}."
                ),
                "",
                "### Routing insight from receptive fields",
                "",
                (
                    "The maximum-gate CIFAR bird<-frog example is an actual frog, so "
                    "that gate identifies source-class evidence rather than a missed "
                    "bird subclass. In Cats vs Dogs, the dog->cat child likewise "
                    "reaches gate 1.000 on an actual dog. Exact correction signs do "
                    "not prevent harm when routing fails out of sample."
                ),
                "",
                "### Capacity conclusion",
                "",
                (
                    f"The CIFAR repeated-seed criterion is "
                    f"{results['CifarSweep']['criterion']} with "
                    f"{results['CifarSweep']['supporting_seeds']}/"
                    f"{results['CifarSweep']['seeds']} supporting seeds. The Cats vs "
                    f"Dogs criterion is {results['PetsSweep']['criterion']} with "
                    f"{results['PetsSweep']['supporting_seeds']}/"
                    f"{results['PetsSweep']['seeds']} support. The contrast is "
                    "reported as dataset/protocol dependence, not as a universal "
                    "double-descent claim."
                ),
                "",
            ]
        )
    lines.extend(
        [
            "## Evidence locations",
            "",
            "- Raw stage records: `outputs/<dataset>/main/metrics.json`.",
            "- Run configuration: `outputs/<dataset>/main/config.json`.",
            "- Pruning metadata: `outputs/<dataset>/main/summary.json`.",
            "- Capacity rows: `outputs/<dataset>/<sweep>/capacity_sweep.json`.",
            "- Figures are stored beside the corresponding JSON.",
            "",
        ]
    )
    (DOCS / "results.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    results = {
        "Cifar": _main_result("cifar10"),
        "Pets": _main_result("catsdogs"),
        "CifarSweep": _sweep_result("cifar10"),
        "PetsSweep": _sweep_result("catsdogs"),
    }
    REPORT.mkdir(exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    _write_macros(results)
    _write_markdown(results)
    print("Wrote report/results_macros.tex and docs/results.md")


if __name__ == "__main__":
    main()
